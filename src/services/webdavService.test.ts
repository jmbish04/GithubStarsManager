import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { WebDAVService } from './webdavService';
import { backend } from './backendAdapter';

vi.mock('./backendAdapter', () => ({
  backend: {
    isAvailable: false,
    proxyWebDAV: vi.fn(),
  },
}));

const proxyWebDAV = vi.mocked(backend.proxyWebDAV);

const config = {
  id: 'webdav-1',
  name: 'My NAS',
  url: 'https://dav.example.com',
  username: 'alice',
  password: 'secret',
  path: '/backup',
  isActive: true,
};

const davService = () => new WebDAVService(config);

describe('WebDAVService transport layer selection', () => {
  beforeEach(() => {
    vi.mocked(backend).isAvailable = false;
    proxyWebDAV.mockReset();
    vi.mocked(window.fetch).mockReset();
    delete window.electronAPI;
  });

  afterEach(() => {
    delete window.electronAPI;
  });

  it('falls back to browser direct connection when no backend is available', async () => {
    vi.mocked(window.fetch).mockResolvedValue(new Response('{}', { status: 200 }));

    await davService().downloadFile('data.json');

    expect(window.fetch).toHaveBeenCalledTimes(1);
    const [url, init] = vi.mocked(window.fetch).mock.calls[0];
    expect(url).toBe('https://dav.example.com/backup/data.json');
    expect(init?.method).toBe('GET');
    expect(proxyWebDAV).not.toHaveBeenCalled();
  });

  it('routes through backend proxy when backend is available, omitting Authorization header', async () => {
    vi.mocked(backend).isAvailable = true;
    proxyWebDAV.mockResolvedValue(new Response('{}', { status: 200 }));

    await davService().downloadFile('data.json');

    expect(window.fetch).not.toHaveBeenCalled();
    const [configId, method, path, body, headers] = proxyWebDAV.mock.calls[0];
    expect(configId).toBe('webdav-1');
    expect(method).toBe('GET');
    expect(path).toBe('/backup/data.json');
    expect(body).toBeUndefined();
    // Authorization is generated by the backend based on config; frontend does not send duplicates
    expect(headers?.Authorization).toBeUndefined();
  });

  it('forwards internal AbortSignal and timeoutMs to backend proxy', async () => {
    vi.mocked(backend).isAvailable = true;
    proxyWebDAV.mockResolvedValue(new Response('{}', { status: 200 }));

    await davService().fileExists('data.json');

    // fileExists creates internal controller; assert signal and timeoutMs are explicitly passed here
    const call = proxyWebDAV.mock.calls[0];
    expect(call[6]).toBeInstanceOf(AbortSignal);
    expect(call[7]).toBeGreaterThan(9000);
    expect(call[7]).toBeLessThanOrEqual(10000);
  });

  it('forwards dynamic timeout calculated by size when uploading', async () => {
    vi.mocked(backend).isAvailable = true;
    proxyWebDAV.mockResolvedValue(new Response('', { status: 201 }));

    const big = 'x'.repeat(2 * 1024 * 1024);
    await davService().uploadFile('big.json', big);

    const putCall = proxyWebDAV.mock.calls.find((call) => call[1] === 'PUT');
    expect(putCall).toBeDefined();
    // 2MB → 2048KB * 100ms = 204800ms, falls within 60s~300s range
    expect(putCall![7]).toBe(204800);
  });

  it('desktop routes via main process IPC without triggering browser fetch or backend proxy', async () => {
    const webdavRequest = vi.fn().mockResolvedValue({
      success: true,
      status: 200,
      statusText: 'OK',
      body: '{"restored":true}',
    });
    window.electronAPI = { webdavRequest } as unknown as Window['electronAPI'];
    vi.mocked(backend).isAvailable = true;

    const restored = await davService().downloadFile('data.json');

    expect(restored).toBe('{"restored":true}');
    expect(window.fetch).not.toHaveBeenCalled();
    expect(proxyWebDAV).not.toHaveBeenCalled();
    const params = webdavRequest.mock.calls[0][0];
    expect(params.url).toBe('https://dav.example.com/backup/data.json');
    expect(params.method).toBe('GET');
    expect(params.headers.Authorization).toMatch(/^Basic /);
  });

  it('desktop normalizes IPC timeout to AbortError, preserving existing timeout message', async () => {
    window.electronAPI = {
      webdavRequest: vi.fn().mockResolvedValue({ success: false, timedOut: true, error: 'timeout' }),
    } as unknown as Window['electronAPI'];

    await expect(davService().downloadFile('data.json')).rejects.toThrow('Download timed out');
  });

  it('desktop PROPFIND preserves 207 status and raw XML', async () => {
    const xml = '<?xml version="1.0"?><D:multistatus xmlns:D="DAV:"><D:response><D:href>/backup/a.json</D:href></D:response></D:multistatus>';
    window.electronAPI = {
      webdavRequest: vi.fn().mockResolvedValue({
        success: true,
        status: 207,
        statusText: 'Multi-Status',
        body: xml,
        contentType: 'application/xml; charset=utf-8',
      }),
    } as unknown as Window['electronAPI'];

    await expect(davService().listFiles()).resolves.toEqual(['a.json']);
  });
});

describe('WebDAVService error messages', () => {
  beforeEach(() => {
    vi.mocked(backend).isAvailable = false;
    proxyWebDAV.mockReset();
    vi.mocked(window.fetch).mockReset();
    delete window.electronAPI;
  });

  afterEach(() => {
    delete window.electronAPI;
  });

  it('desktop provides actionable advice by causeCode (ENOTFOUND -> DNS advice)', async () => {
    window.electronAPI = {
      webdavRequest: vi.fn().mockResolvedValue({
        success: false,
        error: 'undici: fetch failed <- ENOTFOUND: getaddrinfo ENOTFOUND dav.lan',
        causeCode: 'ENOTFOUND',
        causeMessage: 'getaddrinfo ENOTFOUND dav.lan',
      }),
    } as unknown as Window['electronAPI'];

    await expect(davService().testConnection()).rejects.toThrow(/Unable to resolve WebDAV server address/);
  });

  it('desktop network layer failure no longer misreports CORS and retains technical details', async () => {
    window.electronAPI = {
      webdavRequest: vi.fn().mockResolvedValue({
        success: false,
        error: 'undici: fetch failed <- ECONNREFUSED: connect ECONNREFUSED 192.168.1.10:5006',
        causeCode: 'ECONNREFUSED',
        causeMessage: 'connect ECONNREFUSED 192.168.1.10:5006',
      }),
    } as unknown as Window['electronAPI'];

    const attempt = davService().testConnection();
    await expect(attempt).rejects.toThrow(/Server refused the connection/);
    await expect(attempt).rejects.toThrow(/ECONNREFUSED/);
    await expect(attempt).rejects.not.toThrow(/CORS policy blocked/);
  });

  it('desktop provides certificate advice for self-signed certificates', async () => {
    window.electronAPI = {
      webdavRequest: vi.fn().mockResolvedValue({
        success: false,
        error: 'undici: fetch failed <- DEPTH_ZERO_SELF_SIGNED_CERT: self-signed certificate',
        causeCode: 'DEPTH_ZERO_SELF_SIGNED_CERT',
        causeMessage: 'self-signed certificate',
      }),
    } as unknown as Window['electronAPI'];

    await expect(davService().testConnection()).rejects.toThrow(/self-signed certificate/);
  });

  it('desktop normalizes IPC timeout to timeout message', async () => {
    window.electronAPI = {
      webdavRequest: vi.fn().mockResolvedValue({
        success: false,
        timedOut: true,
        error: 'undici: signal timed out',
      }),
    } as unknown as Window['electronAPI'];

    await expect(davService().testConnection()).rejects.toThrow(/Connection timed out/);
  });

  it('pure browser direct connection prompts CORS configuration on Failed to fetch', async () => {
    vi.mocked(window.fetch).mockRejectedValue(new TypeError('Failed to fetch'));

    await expect(davService().testConnection()).rejects.toThrow(/CORS policy blocked/);
  });

  it('pure browser direct connection supports Safari Load failed message', async () => {
    vi.mocked(window.fetch).mockRejectedValue(new TypeError('Load failed'));

    await expect(davService().testConnection()).rejects.toThrow(/CORS policy blocked/);
  });

  it('desktop proxy-related error codes provide proxy troubleshooting advice', async () => {
    window.electronAPI = {
      webdavRequest: vi.fn().mockResolvedValue({
        success: false,
        error: 'chromium: fetch failed <- ERR_PROXY_CONNECTION_FAILED',
        causeCode: 'ERR_PROXY_CONNECTION_FAILED',
      }),
    } as unknown as Window['electronAPI'];

    await expect(davService().testConnection()).rejects.toThrow(/Connection failed via proxy/);
  });

  it('structured causeCode takes precedence over message text classification (ENOTFOUND text + ETIMEDOUT code -> timeout advice)', async () => {
    window.electronAPI = {
      webdavRequest: vi.fn().mockResolvedValue({
        success: false,
        // Primary undici stack reports DNS, fallback chromium stack reports timeout; main process identifies most relevant failure in causeCode
        error: 'undici: fetch failed <- ENOTFOUND: getaddrinfo ENOTFOUND dav.lan; chromium: fetch failed <- ETIMEDOUT: connect timed out',
        causeCode: 'ETIMEDOUT',
      }),
    } as unknown as Window['electronAPI'];

    const attempt = davService().testConnection();
    await expect(attempt).rejects.toThrow(/Connection timed out/);
    await expect(attempt).rejects.not.toThrow(/Unable to resolve/);
  });

  it('prompts direct connection message when electronAPI exists but webdavRequest is not exposed (legacy preload)', async () => {
    // Transport routes via backend/browser direct; error message must not use main process proxy text
    window.electronAPI = {} as unknown as Window['electronAPI'];
    vi.mocked(window.fetch).mockRejectedValue(new TypeError('Failed to fetch'));

    await expect(davService().testConnection()).rejects.toThrow(/CORS policy blocked/);
  });
});

describe('WebDAVService upload retry strategy', () => {
  beforeEach(() => {
    vi.mocked(backend).isAvailable = false;
    proxyWebDAV.mockReset();
    delete window.electronAPI;
  });

  afterEach(() => {
    delete window.electronAPI;
  });

  it('does not retry connection refused (non-transient error)', async () => {
    const webdavRequest = vi.fn().mockResolvedValue({
      success: false,
      error: 'undici: fetch failed <- ECONNREFUSED: connect ECONNREFUSED 192.168.1.10:5006',
      causeCode: 'ECONNREFUSED',
    });
    window.electronAPI = { webdavRequest } as unknown as Window['electronAPI'];

    await expect(davService().uploadFile('a.json', '{}')).rejects.toThrow(/Server refused the connection/);

    const puts = webdavRequest.mock.calls.filter((c) => c[0].method === 'PUT');
    expect(puts.length).toBe(1);
  });

  it('does not retry self-signed certificate (non-transient error)', async () => {
    const webdavRequest = vi.fn().mockResolvedValue({
      success: false,
      error: 'undici: fetch failed <- DEPTH_ZERO_SELF_SIGNED_CERT: self-signed certificate',
      causeCode: 'DEPTH_ZERO_SELF_SIGNED_CERT',
    });
    window.electronAPI = { webdavRequest } as unknown as Window['electronAPI'];

    await expect(davService().uploadFile('a.json', '{}')).rejects.toThrow(/self-signed certificate/);

    const puts = webdavRequest.mock.calls.filter((c) => c[0].method === 'PUT');
    expect(puts.length).toBe(1);
  });

  it('retries connection timeout (transient error) using existing backoff strategy', async () => {
    vi.useFakeTimers();
    try {
      const webdavRequest = vi.fn().mockResolvedValue({
        success: false,
        error: 'undici: fetch failed <- UND_ERR_CONNECT_TIMEOUT: connect timeout',
        causeCode: 'UND_ERR_CONNECT_TIMEOUT',
      });
      window.electronAPI = { webdavRequest } as unknown as Window['electronAPI'];

      const attempt = davService().uploadFile('a.json', '{}');
      const assertion = expect(attempt).rejects.toThrow(/Connection timed out/);
      await vi.runAllTimersAsync();
      await assertion;

      const puts = webdavRequest.mock.calls.filter((c) => c[0].method === 'PUT');
      expect(puts.length).toBe(3);
    } finally {
      vi.useRealTimers();
    }
  });
});

describe('WebDAVService connection test probe order', () => {
  beforeEach(() => {
    vi.mocked(backend).isAvailable = false;
    proxyWebDAV.mockReset();
    vi.mocked(window.fetch).mockReset();
    delete window.electronAPI;
  });

  afterEach(() => {
    delete window.electronAPI;
  });

  it('sends PROPFIND (Depth: 0) first; 207 succeeds without probing HEAD', async () => {
    // Jianguoyun and other servers return 403 for HEAD on collections: successful PROPFIND should not incur an extra 403
    vi.mocked(window.fetch).mockResolvedValue(new Response(null, { status: 207 }));

    await expect(davService().testConnection()).resolves.toBe(true);

    expect(window.fetch).toHaveBeenCalledTimes(1);
    const [url, init] = vi.mocked(window.fetch).mock.calls[0];
    expect(url).toBe('https://dav.example.com/backup');
    expect(init?.method).toBe('PROPFIND');
    expect(init?.headers).toMatchObject({ Depth: '0', Authorization: /^Basic / });
    expect(init?.signal).toBeInstanceOf(AbortSignal);
  });

  it('treats PROPFIND 200 as success as well', async () => {
    vi.mocked(window.fetch).mockResolvedValue(new Response(null, { status: 200 }));

    await expect(davService().testConnection()).resolves.toBe(true);
    expect(window.fetch).toHaveBeenCalledTimes(1);
  });

  it('fails when PROPFIND 207 response body reports target resource 404 (does not falsely report connection available)', async () => {
    const xml = '<?xml version="1.0"?><D:multistatus xmlns:D="DAV:">' +
      '<D:response><D:href>/backup</D:href><D:status>HTTP/1.1 404 Not Found</D:status></D:response>' +
      '</D:multistatus>';
    vi.mocked(window.fetch).mockResolvedValue(new Response(xml, {
      status: 207,
      headers: { 'Content-Type': 'application/xml; charset=utf-8' },
    }));

    await expect(davService().testConnection()).resolves.toBe(false);
  });

  it('treats PROPFIND 207 with only property-level propstat 404 (no resource-level status) as success', async () => {
    // Missing individual properties (e.g. getcontentlength) is normal and does not mean resource is missing
    const xml = '<?xml version="1.0"?><D:multistatus xmlns:D="DAV:">' +
      '<D:response><D:href>/backup</D:href>' +
      '<D:propstat><D:prop><D:getcontentlength/></D:prop>' +
      '<D:status>HTTP/1.1 404 Property Not Found</D:status></D:propstat>' +
      '</D:response></D:multistatus>';
    vi.mocked(window.fetch).mockResolvedValue(new Response(xml, {
      status: 207,
      headers: { 'Content-Type': 'application/xml; charset=utf-8' },
    }));

    await expect(davService().testConnection()).resolves.toBe(true);
  });

  it('PROPFIND 207 exact match on target href: unrelated entry failure does not affect result', async () => {
    // 404 on /old/backup must not match target /backup (loose endsWith would misread entries)
    const xml = '<?xml version="1.0"?><D:multistatus xmlns:D="DAV:">' +
      '<D:response><D:href>/old/backup</D:href><D:status>HTTP/1.1 404 Not Found</D:status></D:response>' +
      '<D:response><D:href>/backup</D:href><D:status>HTTP/1.1 200 OK</D:status></D:response>' +
      '</D:multistatus>';
    vi.mocked(window.fetch).mockResolvedValue(new Response(xml, {
      status: 207,
      headers: { 'Content-Type': 'application/xml; charset=utf-8' },
    }));

    await expect(davService().testConnection()).resolves.toBe(true);
  });

  it('falls back to HEAD when PROPFIND is unavailable (405); HEAD 200 succeeds', async () => {
    vi.mocked(window.fetch)
      .mockResolvedValueOnce(new Response(null, { status: 405 }))
      .mockResolvedValueOnce(new Response(null, { status: 200 }));

    await expect(davService().testConnection()).resolves.toBe(true);

    expect(vi.mocked(window.fetch).mock.calls.map(([, init]) => init?.method)).toEqual(['PROPFIND', 'HEAD']);
    // Fallback HEAD and initial PROPFIND share the same AbortController: 10s timeout covers entire probe
    const [propfindInit, headInit] = vi.mocked(window.fetch).mock.calls.map(([, init]) => init);
    expect(headInit?.signal).toBeInstanceOf(AbortSignal);
    expect(headInit?.signal).toBe(propfindInit?.signal);
  });

  it('still falls back to HEAD when PROPFIND throws a network error (e.g., CORS preflight rejected)', async () => {
    // Browser direct: rejected PROPFIND preflight throws TypeError instead of returning 405
    vi.mocked(window.fetch)
      .mockRejectedValueOnce(new TypeError('Failed to fetch'))
      .mockResolvedValueOnce(new Response(null, { status: 200 }));

    await expect(davService().testConnection()).resolves.toBe(true);
    expect(vi.mocked(window.fetch).mock.calls.map(([, init]) => init?.method)).toEqual(['PROPFIND', 'HEAD']);
  });

  it('does not fall back to HEAD on PROPFIND timeout (AbortError), throws directly as connection timeout', async () => {
    vi.mocked(window.fetch).mockRejectedValueOnce(
      Object.assign(new Error('The operation was aborted'), { name: 'AbortError' }),
    );

    await expect(davService().testConnection()).rejects.toThrow('Connection timed out');
    expect(window.fetch).toHaveBeenCalledTimes(1);
  });

  it('returns false (does not throw) when both PROPFIND and HEAD fail', async () => {
    vi.mocked(window.fetch)
      .mockResolvedValueOnce(new Response(null, { status: 405 }))
      .mockResolvedValueOnce(new Response(null, { status: 500 }));

    await expect(davService().testConnection()).resolves.toBe(false);
  });

  it('10 second budget covers HEAD fallback in browser direct connection (fallback stalls are aborted rather than hanging)', async () => {
    // Fake only setTimeout/clearTimeout/Date (budget and abort timer); do not fake setImmediate to avoid race conditions with mock fetch promise chain.
    vi.useFakeTimers({ toFake: ['setTimeout', 'clearTimeout', 'Date'] });
    try {
      // PROPFIND 405 returns normally; HEAD fallback stalls (simulates fetch listening only to signal)
      vi.mocked(window.fetch)
        .mockResolvedValueOnce(new Response(null, { status: 405 }))
        .mockImplementationOnce((_input, init) => new Promise((_resolve, reject) => {
          init?.signal?.addEventListener('abort', () => reject(new DOMException('The operation was aborted', 'AbortError')));
        }));

      const promise = davService().testConnection();
      const expectation = expect(promise).rejects.toThrow('Connection timed out');
      await vi.advanceTimersByTimeAsync(10001);
      await expectation;
    } finally {
      vi.useRealTimers();
    }
  });

  it('desktop skips HEAD fallback when remaining budget is less than 1s after PROPFIND failure without exceeding total budget', async () => {
    vi.useFakeTimers({ toFake: ['setTimeout', 'clearTimeout', 'Date'] });
    try {
      const webdavRequest = vi.fn(() => new Promise((resolve) => {
        setTimeout(() => resolve({ success: true, status: 405, statusText: '', body: '' }), 9500);
      }));
      window.electronAPI = { webdavRequest } as unknown as Window['electronAPI'];

      const promise = davService().testConnection();
      const expectation = expect(promise).rejects.toThrow('Connection timed out');
      await vi.advanceTimersByTimeAsync(9600);
      await expectation;
      // Fallback skipped due to insufficient remaining budget: only the initial IPC request is made
      expect(webdavRequest).toHaveBeenCalledTimes(1);
    } finally {
      vi.useRealTimers();
      delete window.electronAPI;
    }
  });

  it('fileExists falls back to PROPFIND to confirm existence on HEAD 403 (servers without HEAD support)', async () => {
    vi.mocked(window.fetch)
      .mockResolvedValueOnce(new Response(null, { status: 403 }))
      .mockResolvedValueOnce(new Response(
        '<?xml version="1.0"?><D:multistatus xmlns:D="DAV:"><D:response><D:href>/backup/data.json</D:href></D:response></D:multistatus>',
        { status: 207 },
      ));

    await expect(davService().fileExists('data.json')).resolves.toBe(true);
    expect(vi.mocked(window.fetch).mock.calls.map(([, init]) => init?.method)).toEqual(['HEAD', 'PROPFIND']);
    // Fallback PROPFIND and initial HEAD share the same AbortController; timeout covers entire check
    const [headInit, propfindInit] = vi.mocked(window.fetch).mock.calls.map(([, init]) => init);
    expect(propfindInit?.signal).toBe(headInit?.signal);
  });

  it('fileExists returns false when PROPFIND 207 response body reports target file 404', async () => {
    const xml = '<?xml version="1.0"?><D:multistatus xmlns:D="DAV:">' +
      '<D:response><D:href>/backup/data.json</D:href><D:status>HTTP/1.1 404 Not Found</D:status></D:response>' +
      '</D:multistatus>';
    vi.mocked(window.fetch)
      .mockResolvedValueOnce(new Response(null, { status: 403 }))
      .mockResolvedValueOnce(new Response(xml, {
        status: 207,
        headers: { 'Content-Type': 'application/xml; charset=utf-8' },
      }));

    await expect(davService().fileExists('data.json')).resolves.toBe(false);
  });

  it('fileExists directly treats HEAD 404 as nonexistent without additional probes', async () => {
    vi.mocked(window.fetch).mockResolvedValue(new Response(null, { status: 404 }));

    await expect(davService().fileExists('missing.json')).resolves.toBe(false);
    expect(window.fetch).toHaveBeenCalledTimes(1);
  });
});
